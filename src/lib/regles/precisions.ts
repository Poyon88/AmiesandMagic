//           vérifie qu'elle existe encore) ; "theme" : un sujet transversal.
//   regles  ce qu'un joueur peut observer. N'écrire que ce que le moteur fait
//           réellement, vérifié dans le code ou par un test.
//   sources où la règle a été vérifiée (fichiers sous src/lib/) : pour celui
//           qui la relira, pas pour le joueur — non affiché dans le livret.
//
// Première version (2026-11-20) : tirée des notes de développement, chaque
// règle revérifiée dans le moteur ou ses tests ; quand la note et le code
// divergeaient, c'est le code qui a été écrit.
